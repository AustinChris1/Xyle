/**
 * Free Solana keypair generator for Telegraph x402 (devnet).
 * Usage:
 *   pnpm keys:generate
 *   pnpm keys:generate --write   # appends to .env.local
 */
import { writeFileSync, readFileSync, existsSync } from "fs";
import { generateKeyPairSync } from "crypto";

// Ed25519 keypair via Node crypto (no solana CLI required)
const { privateKey, publicKey } = generateKeyPairSync("ed25519", {
  privateKeyEncoding: { type: "pkcs8", format: "der" },
  publicKeyEncoding: { type: "spki", format: "der" },
});

// PKCS8 DER: last 32 bytes are seed; SPKI: last 32 bytes are public key
const secretSeed = privateKey.subarray(-32);
const pub = publicKey.subarray(-32);

// Solana secret key = 64 bytes (seed + pubkey), base58
const full = Buffer.concat([secretSeed, pub]);

function base58Encode(buffer) {
  const ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
  let zeros = 0;
  while (zeros < buffer.length && buffer[zeros] === 0) zeros++;
  const digits = [0];
  for (let i = zeros; i < buffer.length; i++) {
    let carry = buffer[i];
    for (let j = 0; j < digits.length; j++) {
      carry += digits[j] << 8;
      digits[j] = carry % 58;
      carry = (carry / 58) | 0;
    }
    while (carry > 0) {
      digits.push(carry % 58);
      carry = (carry / 58) | 0;
    }
  }
  let str = "1".repeat(zeros);
  for (let i = digits.length - 1; i >= 0; i--) str += ALPHABET[digits[i]];
  return str;
}

const secretB58 = base58Encode(full);
const pubB58 = base58Encode(pub);

console.log("\n=== Free Solana keypair (devnet) ===\n");
console.log("Public address:", pubB58);
console.log("SOLANA_PRIVATE_KEY (base58):", secretB58);
console.log("\n1) Fund SOL:  https://faucet.solana.com  (Devnet)");
console.log("2) Fund USDC: devnet mint 4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU");
console.log("3) See KEYS.md for details\n");
console.log("NEVER commit this key. NEVER use a funded mainnet wallet.\n");

if (process.argv.includes("--write")) {
  const path = ".env.local";
  let existing = existsSync(path) ? readFileSync(path, "utf8") : "";
  const block = [
    "",
    "# Generated by pnpm keys:generate --write",
    `SOLANA_PRIVATE_KEY=${secretB58}`,
    "SOLANA_NETWORK=devnet",
    "FORCE_MOCK=false",
    "TELEGRAPH_BASE_URL=http://54.252.48.30:7044",
    "",
  ].join("\n");

  if (existing.includes("SOLANA_PRIVATE_KEY=")) {
    existing = existing.replace(
      /^SOLANA_PRIVATE_KEY=.*$/m,
      `SOLANA_PRIVATE_KEY=${secretB58}`
    );
    if (!existing.includes("FORCE_MOCK=")) {
      existing += "\nFORCE_MOCK=false\n";
    }
    writeFileSync(path, existing);
    console.log("Updated SOLANA_PRIVATE_KEY in .env.local");
  } else {
    writeFileSync(path, existing + block);
    console.log("Appended key + defaults to .env.local");
  }
}
